// The window-close handshake: the webview answers the host's deferred
// CloseRequested event with its decision, and the host exits only on approval.
fn cmd_resolve_close(
    cfg: &specta_typescript::Typescript,
    type_map: &mut TypeCollection,
) -> Result<String, Box<dyn Error>> {
    let err = ty::<ContractError>(cfg, type_map)?;
    Ok(cmd_fn(
        CmdSpec {
            name: "resolveClose",
            invoke: "resolve_close",
            arg_obj: Some("{ approved }"),
        },
        &[("approved", "boolean".to_string())],
        &format!("Result<null, {err}>"),
    ))
}

#[derive(Clone, Copy)]
struct CmdSpec<'a> {
    name: &'a str,
    invoke: &'a str,
    arg_obj: Option<&'a str>,
}

fn cmd_fn(spec: CmdSpec<'_>, args: &[(&str, String)], ret: &str) -> String {
    let args_str = args
        .iter()
        .map(|(n, t)| format!("{}: {}", n.to_lower_camel_case(), t))
        .collect::<Vec<_>>()
        .join(", ");
    let arg_usage = spec.arg_obj.map(|s| format!(", {s}")).unwrap_or_default();
    format!(
        "async {}({args_str}) : Promise<{ret}> {{\n    try {{\n    return {{ status: \"ok\", data: await TAURI_INVOKE(\"{}\"{arg_usage}) }};\n}} catch (e) {{\n    if(e instanceof Error) throw e;\n    else return {{ status: \"error\", error: e  as any }};\n}}\n}}",
        spec.name, spec.invoke
    )
}

fn ty<T: Type + 'static>(
    cfg: &specta_typescript::Typescript,
    type_map: &mut TypeCollection,
) -> Result<String, specta_typescript::ExportError> {
    datatype_str(cfg, <T as Type>::inline(type_map, Generics::NONE), type_map)
}

#[derive(Clone, Copy)]
enum ArgTy {
    Str,
}

struct CmdOneSpec<'a> {
    name: &'a str,
    invoke: &'a str,
    arg_obj: Option<&'a str>,
    arg: (&'a str, Option<ArgTy>),
}

impl<'a> CmdOneSpec<'a> {
    const fn new(
        name: &'a str,
        invoke: &'a str,
        arg_obj: Option<&'a str>,
        arg: (&'a str, Option<ArgTy>),
    ) -> Self {
        Self {
            name,
            invoke,
            arg_obj,
            arg,
        }
    }
}

fn arg_type<A: Type + 'static>(
    cfg: &specta_typescript::Typescript,
    type_map: &mut TypeCollection,
    kind: Option<ArgTy>,
) -> Result<String, Box<dyn Error>> {
    Ok(match kind {
        Some(ArgTy::Str) => "string".to_string(),
        None => ty::<A>(cfg, type_map)?,
    })
}

fn cmd_noarg<R: Type + 'static>(
    cfg: &specta_typescript::Typescript,
    type_map: &mut TypeCollection,
    name: &'static str,
    invoke: &'static str,
) -> Result<String, Box<dyn Error>> {
    let err = ty::<ContractError>(cfg, type_map)?;
    let ok = ty::<R>(cfg, type_map)?;
    Ok(cmd_fn(
        CmdSpec {
            name,
            invoke,
            arg_obj: None,
        },
        &[],
        &format!("Result<{ok}, {err}>"),
    ))
}

fn cmd_one<R, A>(
    cfg: &specta_typescript::Typescript,
    type_map: &mut TypeCollection,
    spec: CmdOneSpec<'_>,
) -> Result<String, Box<dyn Error>>
where
    R: Type + 'static,
    A: Type + 'static,
{
    let err = ty::<ContractError>(cfg, type_map)?;
    let ok = ty::<R>(cfg, type_map)?;
    let (arg_name, kind) = spec.arg;
    let args = vec![(arg_name, arg_type::<A>(cfg, type_map, kind)?)];
    Ok(cmd_fn(
        CmdSpec {
            name: spec.name,
            invoke: spec.invoke,
            arg_obj: spec.arg_obj,
        },
        &args,
        &format!("Result<{ok}, {err}>"),
    ))
}

